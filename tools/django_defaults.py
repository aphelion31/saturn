"""Emit SQL column DEFAULTs for Plane's Django models.

Django fills defaults in Python, so Plane's tables have NOT NULL columns with no
database default. Saturn writes plain SQL, so it needs them in the database.
Adding DB defaults does not change Django's behaviour (Django always sends a value).

Run inside Plane's api env (Saturn does not need this at runtime):
  cd ../plane/apps/api && SECRET_KEY=x DATABASE_URL=postgres://localhost/x \
    uv run python ../../../saturn/tools/django_defaults.py > ../../../saturn/migrations/0002_defaults.sql
"""
import json, os, sys, uuid
sys.path.insert(0, os.getcwd())
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "plane.settings.local")
import django
django.setup()
from django.apps import apps
from django.db import models
from django.utils import timezone

def lit(f, v):
    if v is None:
        return None
    if isinstance(f, models.JSONField):
        return "'" + json.dumps(v).replace("'", "''") + "'::jsonb"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    return None

out = ["-- Generated by tools/django_defaults.py. Database defaults mirroring Django model defaults.", ""]
for m in apps.get_models():
    if m._meta.proxy or not m._meta.managed:
        continue
    t = m._meta.db_table
    for f in m._meta.concrete_fields:
        col, sql = f.column, None
        if isinstance(f, (models.DateTimeField, models.DateField)) and (getattr(f, "auto_now", False) or getattr(f, "auto_now_add", False)):
            sql = "now()"
        elif f.has_default():
            d = f.default
            if d is uuid.uuid4:
                sql = "gen_random_uuid()"
            elif d is timezone.now:
                sql = "now()"
            elif callable(d):
                name = getattr(d, "__name__", "")
                if d in (dict, list) or name.startswith("get_default") or name.endswith("_props") or name.startswith("get_"):
                    try:
                        sql = lit(f, d())
                    except Exception:
                        sql = None
            else:
                sql = lit(f, d)
        if sql:
            out.append(f'ALTER TABLE ONLY public."{t}" ALTER COLUMN "{col}" SET DEFAULT {sql};')
print("\n".join(out))
